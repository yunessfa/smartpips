from django.conf import settings
from django.db import models


class TradeQuerySet(models.QuerySet):
    def update(self, **kwargs):
        if {"entry_snapshot", "entry_snapshot_hash"}.intersection(kwargs):
            raise ValueError("Entry snapshot is immutable.")
        return super().update(**kwargs)

    def bulk_create(self, objs, **kwargs):
        # No silent bypass of creation snapshots/events.
        raise ValueError("Use individual Trade.save() for audited creation.")


class Trade(models.Model):
    objects = TradeQuerySet.as_manager()
    entry_snapshot = models.JSONField(default=dict, blank=True, editable=False)
    entry_snapshot_hash = models.CharField(max_length=64, blank=True, editable=False)

    def save(self, *args, **kwargs):
        from django.db import transaction
        from .snapshots import build, digest
        with transaction.atomic():
            previous = type(self).objects.select_for_update().filter(pk=self.pk).first() if self.pk else None
            if previous:
                if previous.entry_snapshot:
                    immutable = ("entry_price", "size", "leverage", "symbol", "direction", "source",
                                 "strategy_name", "strategy_version", "timeframe", "confidence")
                    if any(getattr(previous, k) != getattr(self, k) for k in immutable):
                        raise ValueError("Entry facts are immutable. Correct via a separately audited amendment, not overwrite.")
                if (self.entry_snapshot != previous.entry_snapshot or
                        self.entry_snapshot_hash != previous.entry_snapshot_hash):
                    raise ValueError("Entry snapshot is immutable; historical unknowns must stay unknown.")
            else:
                if self.entry_snapshot or self.entry_snapshot_hash:
                    raise ValueError("Entry snapshot must be generated by the server.")
                self.entry_snapshot = build(self, getattr(self, "_entry_analysis", None))
                self.entry_snapshot_hash = digest(self.entry_snapshot)
            super().save(*args, **kwargs)
            if previous is None:
                TradeEvent.objects.create(trade=self, event="ENTRY", details={
                    "snapshot_hash": self.entry_snapshot_hash, "execution_verified": self.execution_verified})
            else:
                for field in ("stop_loss", "take_profit", "status", "tp1_done", "tp2_done", "tp3_done"):
                    old = getattr(previous, field)
                    new = getattr(self, field)
                    if old != new and (not kwargs.get("update_fields") or field in kwargs["update_fields"]):
                        TradeEvent.objects.create(trade=self, event="EXIT" if field == "status" and new == "closed" else "STATE_CHANGED",
                            details={"field": field, "old": old, "new": new, "reason": self.exit_reason or "not_recorded"})

    DIRECTION = [("long", "Long"), ("short", "Short")]
    STATUS = [("open", "Open"), ("closed", "Closed")]

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, related_name="trades", on_delete=models.CASCADE
    )

    symbol = models.CharField(max_length=40)                # e.g. BTCUSDT
    tradingview_symbol = models.CharField(max_length=60, blank=True)
    direction = models.CharField(max_length=8, choices=DIRECTION, default="long")

    entry_price = models.FloatField()
    exit_price = models.FloatField(null=True, blank=True)
    take_profit = models.FloatField(null=True, blank=True)
    stop_loss = models.FloatField(null=True, blank=True)

    # Optional 3-level partial take-profit plan. When set, auto_close closes a
    # PORTION of the position at each level instead of the whole trade at once —
    # so a position is still managed (partially banked, stop trailed) even if the
    # user isn't watching. tp_done tracks which levels have already fired.
    tp1_price = models.FloatField(null=True, blank=True)
    tp1_pct = models.FloatField(default=40)
    tp1_done = models.BooleanField(default=False)
    tp2_price = models.FloatField(null=True, blank=True)
    tp2_pct = models.FloatField(default=35)
    tp2_done = models.BooleanField(default=False)
    tp3_price = models.FloatField(null=True, blank=True)
    tp3_pct = models.FloatField(default=25)
    tp3_done = models.BooleanField(default=False)
    # remaining fraction of the ORIGINAL size still open (1.0 = nothing closed yet)
    remaining_pct = models.FloatField(default=100)
    # realised P&L banked so far from partial closes (added to final pnl on full close)
    realized_pnl = models.FloatField(default=0)

    # Position size in quote currency (e.g. USDT margin the user committed).
    size = models.FloatField(default=0)
    leverage = models.FloatField(default=1)

    status = models.CharField(max_length=8, choices=STATUS, default="open")

    # Realised P&L (filled when the trade is closed).
    pnl = models.FloatField(null=True, blank=True)
    pnl_percent = models.FloatField(null=True, blank=True)

    # Where the idea came from (e.g. "assistant" or "manual").
    source = models.CharField(max_length=20, default="manual")
    setup_class = models.CharField(max_length=30, blank=True)  # e.g. trend_continuation
    notes = models.TextField(blank=True)

    # --- Attribution -------------------------------------------------------
    # Which configured strategy produced this trade. The FK is SET_NULL and the
    # name/version are ALSO stored as plain text on purpose: a strategy can be
    # archived or renamed years later, and journal history must still say what
    # actually generated the trade. Trades opened before this feature (or by
    # hand) simply leave these blank and are reported as "Unassigned".
    strategy = models.ForeignKey(
        "strategy.Strategy", null=True, blank=True,
        on_delete=models.SET_NULL, related_name="trades",
    )
    strategy_name = models.CharField(max_length=80, blank=True)
    strategy_version = models.PositiveIntegerField(null=True, blank=True)

    # Context the engine had at entry, shown in the trade detail view.
    timeframe = models.CharField(max_length=10, blank=True)      # e.g. "5m"
    confidence = models.FloatField(null=True, blank=True)        # 0-100 at entry
    exit_reason = models.CharField(max_length=40, blank=True)    # tp1 / sl / manual / ...
    # Additive provenance only. Unknown historical costs stay NULL, never zero.
    fees_paid = models.FloatField(null=True, blank=True)
    funding_paid = models.FloatField(null=True, blank=True)  # signed cost; negative = credit
    costs_verified = models.BooleanField(default=False)
    execution_verified = models.BooleanField(default=False)
    external_order_id = models.CharField(max_length=80, blank=True)
    external_position_id = models.CharField(max_length=80, blank=True)
    execution_evidence = models.JSONField(default=dict, blank=True)

    @property
    def net_pnl(self):
        if (self.pnl is None or not self.costs_verified or self.fees_paid is None
                or self.funding_paid is None):
            return None
        return round(self.pnl - self.fees_paid - self.funding_paid, 4)

    @property
    def pnl_basis(self):
        if self.source == "bitunix_real":
            return "exchange_verified" if self.execution_verified else "estimated_unverified"
        return "simulated_gross"

    opened_at = models.DateTimeField(auto_now_add=True)
    closed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-opened_at"]

    def compute_pnl(self):
        """Return (pnl_quote, pnl_percent) for the current/exit price.

        Percentage is on the raw price move; pnl_quote scales it by the
        leveraged notional (size * leverage).
        """
        if self.exit_price is None or not self.entry_price:
            return None, None
        if self.direction == "long":
            move = (self.exit_price - self.entry_price) / self.entry_price
        else:
            move = (self.entry_price - self.exit_price) / self.entry_price
        pct = move * 100 * (self.leverage or 1)
        notional = (self.size or 0) * (self.leverage or 1)
        pnl = notional * move
        return round(pnl, 4), round(pct, 4)

    def close(self, exit_price, reason="manual"):
        from django.utils import timezone
        from django.db import transaction
        # Lock/reload persisted state: repeated closes and overlapping polling
        # requests must neither settle twice nor overwrite another partial exit.
        with transaction.atomic():
            locked = type(self).objects.select_for_update().get(pk=self.pk)
            if locked.status == "closed":
                self.__dict__.update(locked.__dict__)
                return
            self.__dict__.update(locked.__dict__)
            self._finish(exit_price, reason)

    def _finish(self, exit_price, reason):
        from django.utils import timezone
        self.exit_price = exit_price
        pnl, pct = self.compute_pnl()
        self.pnl = round((pnl or 0) * max(0, self.remaining_pct) / 100
                         + (self.realized_pnl or 0), 4)
        self.pnl_percent = round(self.pnl / self.size * 100, 4) if self.size else None
        self.remaining_pct = 0
        self.exit_reason = reason
        self.status = "closed"
        self.closed_at = timezone.now()
        self.save()

    def close_partial(self, exit_price, pct_of_original, level_field):
        """Bank profit on a PORTION of the position (a TP1/TP2/TP3 hit) without
        fully closing the trade. Reduces remaining_pct and stores the realised
        P&L for that slice; the rest of the position keeps running toward the
        next level or the stop."""
        from django.db import transaction
        import math
        allowed = {"tp1_done", "tp2_done", "tp3_done"}
        if level_field not in allowed or not math.isfinite(float(pct_of_original)) or pct_of_original <= 0:
            raise ValueError("Invalid partial exit")
        with transaction.atomic():
            locked = type(self).objects.select_for_update().get(pk=self.pk)
            self.__dict__.update(locked.__dict__)
            if self.status == "closed" or getattr(self, level_field):
                return 0.0
            return self._partial(exit_price, pct_of_original, level_field)

    def _partial(self, exit_price, pct_of_original, level_field):
        pct_of_original = min(float(pct_of_original), max(0, self.remaining_pct))
        if self.direction == "long":
            move = (exit_price - self.entry_price) / self.entry_price
        else:
            move = (self.entry_price - exit_price) / self.entry_price
        notional = (self.size or 0) * (self.leverage or 1)
        slice_pnl = notional * move * (pct_of_original / 100.0)

        self.realized_pnl = round((self.realized_pnl or 0) + slice_pnl, 4)
        self.remaining_pct = round(max(0, self.remaining_pct - pct_of_original), 2)
        setattr(self, level_field, True)  # e.g. tp1_done = True

        if self.remaining_pct <= 0:
            # all three slices banked -> fully close at this last level's price
            self._finish(exit_price, "tp_final")
        else:
            self.save()
        return slice_pnl

    def __str__(self):
        return f"{self.direction} {self.symbol} @ {self.entry_price}"


class EventQuerySet(models.QuerySet):
    def update(self, **kwargs):
        raise ValueError("Trade events are append-only.")
    def delete(self):
        raise ValueError("Trade events are append-only.")


class TradeEvent(models.Model):
    objects = EventQuerySet.as_manager()
    trade = models.ForeignKey(Trade, related_name="events", on_delete=models.CASCADE)
    created_at = models.DateTimeField(auto_now_add=True)
    event = models.CharField(max_length=32)
    details = models.JSONField(default=dict)
    class Meta:
        ordering = ["created_at", "pk"]
    def save(self, *args, **kwargs):
        if not self._state.adding:
            raise ValueError("Trade events are append-only.")
        return super().save(*args, **kwargs)
    def delete(self, *args, **kwargs):
        raise ValueError("Trade events are append-only.")
